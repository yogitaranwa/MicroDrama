def plan_route(requirements: dict, registry: dict[str, Route] | None = None,
               overrides: dict | None = None) -> dict:
    """Check which routes may carry a shot with these hard requirements.

    requirements: mapping of requirement flag -> bool. Only truthy flags
    constrain routing. Optional non-flag keys: "seconds" (shot duration),
    "references" (number of references the shot needs).
    overrides: {route_name: {"operator": str, "reason": str, "at": str}}.
    An override without a named operator and reason is ignored.
    """
    registry = registry or default_registry()
    overrides = overrides or {}
    active = [flag for flag, on in requirements.items()
              if flag in REQUIREMENT_CAPABILITY and on]
    unknown_flags = sorted(set(requirements) - set(REQUIREMENT_CAPABILITY)
                           - {"seconds", "references"})
    if unknown_flags:
        raise ValueError(f"unknown requirement flags: {unknown_flags}")
    seconds = requirements.get("seconds")
    references = requirements.get("references", 0)
    if not isinstance(references, int) or references < 0:
        raise ValueError("references must be a non-negative integer")

    report = {"requirements": active, "routes": []}
    for name, route in sorted(registry.items()):
        blocked, cautions = [], []
        for flag in active:
            label = route.capabilities[REQUIREMENT_CAPABILITY[flag]]
            if label == "unsupported":
                blocked.append(f"{flag}: {name} has project evidence of failure")
            elif label == "unverified":
                cautions.append(f"{flag}: {name} mechanism unverified in this project")
        if route.max_seconds is not None and seconds is not None and seconds > route.max_seconds:
            blocked.append(f"duration {seconds}s exceeds {name} max {route.max_seconds}s")
        if references > route.reference_slots:
            blocked.append(f"needs {references} references; {name} takes {route.reference_slots}")
        status = "blocked" if blocked else ("caution" if cautions else "allowed")
        if blocked and name in overrides:
            override = overrides[name]
            if override.get("operator") and override.get("reason"):
                status = "override"
                cautions.append(f"operator override by {override['operator']}: "
                                f"{override['reason']}; evidence of failure still stands")
        report["routes"].append({
            "route": name,
            "status": status,
            "blocked_reasons": blocked,
            "cautions": cautions,
            "evidence": list(route.evidence),
        })
    if not any(r["status"] in ("allowed", "caution", "override") for r in report["routes"]):
        report["status"] = "no_route"
    else:
        report["status"] = "ok"
    return report
