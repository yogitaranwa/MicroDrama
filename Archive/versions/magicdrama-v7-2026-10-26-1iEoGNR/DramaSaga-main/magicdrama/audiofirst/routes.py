"""Generation-route capability registry for planning.

Capabilities are evidence labels, not quality claims:
- "supported": working mechanism exists.
- "unverified": mechanism on paper, no accepted result in this project.
- "unsupported": project evidence shows the route failing the
  requirement. Hard requirements block such routes unless a named
  operator records an explicit risk override; code never manufactures
  one. No label is a media-quality verdict: acceptance still requires
  review of the generated bytes.
"""
from __future__ import annotations

from dataclasses import dataclass, field

CAPABILITIES = (
    "camera_control",
    "eyeline_control",
    "wardrobe_control",
    "prop_action",
    "audio_conditioning",
    "structure_controls",
)
LABELS = ("supported", "unverified", "unsupported")

REQUIREMENT_CAPABILITY = {
    "locked_camera": "camera_control",
    "off_lens_eyelines": "eyeline_control",
    "exact_wardrobe": "wardrobe_control",
    "scripted_action": "prop_action",
    "audio_led_performance": "audio_conditioning",
    "masked_or_structured_edit": "structure_controls",
}


@dataclass(frozen=True)
class Route:
    name: str
    capabilities: dict[str, str]
    reference_slots: int
    max_seconds: float | None
    notes: str = ""
    evidence: tuple[str, ...] = field(default=())

    def __post_init__(self):
        if set(self.capabilities) != set(CAPABILITIES):
            raise ValueError(f"route {self.name} must declare exactly {list(CAPABILITIES)}")
        for key, value in self.capabilities.items():
            if value not in LABELS:
                raise ValueError(f"route {self.name} capability {key} has bad label {value!r}")
        if self.reference_slots < 0:
            raise ValueError("reference_slots cannot be negative")
        if self.max_seconds is not None and self.max_seconds <= 0:
            raise ValueError("max_seconds must be positive")


